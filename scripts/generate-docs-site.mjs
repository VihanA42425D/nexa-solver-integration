import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const DOCS = join(ROOT, "docs-site", "docs");
const GENERATED = join(DOCS, "generated");

const readJson = async (relativePath) => JSON.parse(
  await readFile(join(ROOT, relativePath), "utf8"),
);

const markdownCell = (value) => String(value ?? "?")
  .replaceAll("|", "\\|")
  .replaceAll("\n", " ");

const inlineCode = (value) => value == null || value === ""
  ? "?"
  : `\`${markdownCell(value)}\``;

const link = (label, url) => url
  ? `[${markdownCell(label)}](${url})`
  : markdownCell(label);

const table = (headers, rows) => [
  `| ${headers.join(" | ")} |`,
  `| ${headers.map(() => "---").join(" | ")} |`,
  ...rows.map((row) => `| ${row.map(markdownCell).join(" | ")} |`),
].join("\n");

const writeGenerated = async (name, title, sourcePaths, body) => {
  const sourceList = sourcePaths.map((path) => `\`${path}\``).join(", ");
  const content = [
    `<!-- Generated by scripts/generate-docs-site.mjs from ${sourceList}. Do not edit. -->`,
    "",
    `### ${title}`,
    "",
    body,
    "",
  ].join("\n");
  await writeFile(join(GENERATED, name), content, "utf8");
};

const generateApi = async () => {
  const openapi = await readJson("openapi/openapi.json");
  const methods = new Set(["get", "post", "put", "patch", "delete", "head", "options"]);
  const rows = [];
  for (const [path, pathItem] of Object.entries(openapi.paths ?? {})) {
    for (const [method, operation] of Object.entries(pathItem)) {
      if (!methods.has(method) || !operation || typeof operation !== "object") continue;
      rows.push([
        `\`${method.toUpperCase()}\``,
        `\`${path}\``,
        operation.summary ?? operation.operationId ?? "?",
        operation.operationId ? `\`${operation.operationId}\`` : "?",
      ]);
    }
  }
  await writeGenerated(
    "api-paths.md",
    `${openapi.info?.title ?? "Nexa V6 API"} operations`,
    ["openapi/openapi.json"],
    table(["Method", "Path", "Purpose", "Operation ID"], rows),
  );
};

const generateNetworksAndContracts = async () => {
  const networkIds = await readJson("networks/network-ids.json");
  const bundle = await readJson("nexa-mainnet-v6.json");
  const networkRows = Object.entries(networkIds.networks ?? {}).map(([slug, network]) => {
    const deployment = bundle.networks?.[slug] ?? {};
    const verificationUrl = deployment.verification?.sourcify?.url
      ?? deployment.verification?.explorer?.url;
    return [
      network.name,
      inlineCode(network.chainId),
      inlineCode(network.networkId),
      inlineCode(deployment.systemState?.routeCount),
      deployment.systemState?.live === true ? "Active" : "Check canonical state",
      verificationUrl ? link("Evidence", verificationUrl) : "Canonical fingerprint",
    ];
  });

  const contractRows = [
    ...Object.entries(bundle.contracts ?? {}).map(([name, contract]) => [
      `\`${name}\``,
      inlineCode(contract.address ?? contract.facadeAddress),
      inlineCode(contract.runtimeCodeHash ?? contract.expectedRuntimeCodeHash),
      contract.abiPath ? inlineCode(contract.abiPath) : "Canonical bundle",
    ]),
    ...Object.entries(bundle.standards ?? {}).map(([key, standard]) => [
      `\`${standard.name ?? key.toUpperCase()} module\``,
      inlineCode(standard.moduleAddress),
      inlineCode(standard.runtimeCodeHash),
      inlineCode("standards/nexa-standards.json"),
    ]),
  ];

  const body = [
    "#### Supported networks",
    "",
    table(["Network", "Chain ID", "Network ID", "Published routes", "State", "Verification"], networkRows),
    "",
    "#### Solver-facing contracts",
    "",
    table(["Contract", "Address", "Runtime code hash", "ABI source"], contractRows),
    "",
    `Release ID: ${inlineCode(bundle.releaseId)}. Addresses marked as the same across chains are still verified independently on each chain.`,
  ].join("\n");

  await writeGenerated(
    "networks-contracts.md",
    "Canonical Mainnet V6 projection",
    ["networks/network-ids.json", "nexa-mainnet-v6.json"],
    body,
  );
};

const generateSdk = async () => {
  const contract = await readJson("sdk-spec/nexa-v6-sdk-contract.json");
  const rows = (contract.operations ?? []).map((operation) => [
    inlineCode(operation.name),
    inlineCode(operation.input),
    inlineCode(operation.output),
  ]);
  const body = [
    `SDK contract: ${inlineCode(contract.schema)} ? spec version ${inlineCode(contract.specVersion)} ? status ${inlineCode(contract.status)}.`,
    "",
    table(["Operation", "Input", "Output"], rows),
  ].join("\n");
  await writeGenerated(
    "sdk-operations.md",
    "Canonical SDK operations",
    ["sdk-spec/nexa-v6-sdk-contract.json"],
    body,
  );
};

const generateStandards = async () => {
  const manifest = await readJson("standards/nexa-standards.json");
  const rows = Object.values(manifest.standards ?? {}).map((standard) => [
    standard.name,
    inlineCode(standard.standardId),
    inlineCode(standard.compatibilityLevel),
    standard.executable === true ? "Yes" : "No",
    inlineCode(standard.moduleAddress),
    inlineCode(standard.resolutionTransport),
  ]);
  const body = [
    table(["Standard", "Standard ID", "Compatibility", "Executable", "Module", "Transport"], rows),
    "",
    `Supported chain IDs: ${(manifest.supportedChainIds ?? []).map(inlineCode).join(", ")}. Router source transaction count: ${inlineCode(manifest.router?.sourceTransactionCount)}.`,
  ].join("\n");
  await writeGenerated(
    "standards.md",
    "Canonical standards projection",
    ["standards/nexa-standards.json"],
    body,
  );
};

const generateIndexing = async () => {
  const manifest = await readJson("indexing/indexing-manifest.json");
  const rows = (manifest.networks ?? []).map((network) => {
    const graph = manifest.graph?.deployments?.[network.graphNetwork] ?? {};
    const substreams = manifest.substreams?.deployments?.[network.graphNetwork] ?? {};
    const graphStatus = network.subgraphSupported
      ? link(graph.studioStatus ?? "Supported", graph.developmentQueryUrl)
      : "Unsupported (use Substreams)";
    const substreamsStatus = link(
      substreams.registryStatus ?? "See manifest",
      substreams.registryUrl ?? substreams.spkgUrl,
    );
    return [
      inlineCode(network.graphNetwork),
      inlineCode(network.chainId),
      graphStatus,
      substreamsStatus,
      inlineCode(network.indexingMode),
    ];
  });
  const infra = manifest.externalInfrastructure ?? {};
  const body = [
    table(["Network", "Chain ID", "Graph", "Substreams", "Mode"], rows),
    "",
    `Authority: **non-authoritative**. Hosting: ${inlineCode(infra.hosting)}. RPC consumption: ${inlineCode(infra.rpcConsumption)}. Self-hosted: ${inlineCode(infra.selfHosted)}. Nexa runtime RPC used: ${inlineCode(infra.nexaRpcUsed)}.`,
  ].join("\n");
  await writeGenerated(
    "indexing.md",
    "Canonical external indexing projection",
    ["indexing/indexing-manifest.json"],
    body,
  );
};

await mkdir(GENERATED, { recursive: true });
await mkdir(join(DOCS, "assets"), { recursive: true });
await Promise.all([
  generateApi(),
  generateNetworksAndContracts(),
  generateSdk(),
  generateStandards(),
  generateIndexing(),
  copyFile(join(ROOT, "openapi", "openapi.json"), join(DOCS, "assets", "openapi.json")),
]);

console.log("Generated Nexa documentation projections from canonical artifacts.");
